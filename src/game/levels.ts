// Legend for ASCII level grids (each row must be identical width, 15 rows tall):
// '.' = empty air
// '#' = ground block
// 'B' = breakable brick block
// '?' = mystery block (coin)
// 'M' = mystery block with Mushroom / Fire Flower
// 'S' = mystery block with Starman
// 'U' = mystery block with 1-UP
// 'C' = floating coin
// 'X' = hard stone / staircase block
// '=' = bridge / thin platform
// '[' = pipe top-left, ']' = pipe top-right
// '(' = piranha pipe top-left, ')' = piranha pipe top-right
// '{' = pipe body-left, '}' = pipe body-right
// 'G' = Goomba (Cogumelo-Brabo)
// 'K' = Koopa (Tartaruga Casco-Verde)
// 'W' = Winged Para-Koopa (Besouro Alado)
// 'P' = Player spawn (open ground guaranteed around spawn)
// 'F' = Flagpole base
// 'H' = Castle door / finish anchor

function padRows(rawRows: string[]): string[] {
  const maxLen = Math.max(...rawRows.map((r) => r.length));
  return rawRows.map((r) => r.padEnd(maxLen, '.'));
}

